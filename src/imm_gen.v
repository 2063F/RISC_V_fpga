// =============================================================================
// imm_gen.v - Immediate Generator for RISC-V RV32I CPU
// =============================================================================
// Extracts and sign-extends the immediate value from the instruction based on
// the instruction format.
// =============================================================================

`include "riscv_defines.vh"

module imm_gen (
    input  wire [31:0] inst,      // 32-bit instruction
    input  wire [2:0]  imm_type,  // Immediate type from decoder
    output reg  [31:0] imm        // Sign-extended immediate value
);

    always @(*) begin
        case (imm_type)
            // ------------------------------------------------------------------
            // I-type: ADDI, SLTI, LW, JALR, etc.
            // imm[11:0] = inst[31:20]
            // ------------------------------------------------------------------
            `IMM_I: imm = {{20{inst[31]}}, inst[31:20]};

            // ------------------------------------------------------------------
            // S-type: SW, SH, SB
            // imm[11:5] = inst[31:25], imm[4:0] = inst[11:7]
            // ------------------------------------------------------------------
            `IMM_S: imm = {{20{inst[31]}}, inst[31:25], inst[11:7]};

            // ------------------------------------------------------------------
            // B-type: BEQ, BNE, BLT, BGE, etc.
            // imm[12] = inst[31], imm[11] = inst[7], imm[10:5] = inst[30:25], imm[4:1] = inst[11:8], imm[0] = 0
            // ------------------------------------------------------------------
            `IMM_B: imm = {{20{inst[31]}}, inst[7], inst[30:25], inst[11:8], 1'b0};

            // ------------------------------------------------------------------
            // U-type: LUI, AUIPC
            // imm[31:12] = inst[31:12], imm[11:0] = 0
            // ------------------------------------------------------------------
            `IMM_U: imm = {inst[31:12], 12'd0};

            // ------------------------------------------------------------------
            // J-type: JAL
            // imm[20] = inst[31], imm[19:12] = inst[19:12], imm[11] = inst[20], imm[10:1] = inst[30:21], imm[0] = 0
            // ------------------------------------------------------------------
            `IMM_J: imm = {{12{inst[31]}}, inst[19:12], inst[20], inst[30:21], 1'b0};

            default: imm = 32'd0;
        endcase
    end

endmodule
